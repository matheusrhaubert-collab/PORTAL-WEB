  function wrapSave() {
    if (typeof window.savePhotorealRenderToProject !== 'function' || window.savePhotorealRenderToProject.__aiR) return;
    const orig = window.savePhotorealRenderToProject;
    const wrapped = async function (dataUrl, opts) {
      const r = await orig.apply(this, arguments);
      const ehPrint = !!(opts && opts.kind === 'print');
      if (pending && !ehPrint) {
        pending = false;
        let baseUrl = null;
        try { baseUrl = (typeof projectPhotorealPhotos !== 'undefined' && projectPhotorealPhotos[0]) ? projectPhotorealPhotos[0].image_url : null; } catch (e) { baseUrl = null; }
        const cam = window.__lastPhotorealCamera || null;
        setTimeout(() => {
          const c = document.getElementById('po-photoreal-close');
          if (c) c.click();
          runAi(baseUrl || dataUrl, cam);
        }, 600);
      }
      return r;
    };
    wrapped.__aiR = true;
    window.savePhotorealRenderToProject = wrapped;
  }

  async function runAi(baseUrl, cam) {
    openModal();
    resetView();
    state = { baseUrl, camera: cam, aiDataUrl: null };
    const baseImg = q('po-aiR-base');
    baseImg.src = baseUrl; baseImg.style.display = 'block';
    setStatus(t('step2'));
    try {
      const baseDataUrl = baseUrl.startsWith('data:') ? baseUrl : await blobToDataUrl(await (await fetch(baseUrl, { cache: 'no-store' })).blob());
      let aspectRatio = null;
      try {
        const ratio = await getImageAspectRatio(baseDataUrl);
        aspectRatio = (typeof nearestSupportedAspectRatio === 'function') ? nearestSupportedAspectRatio(ratio) : null;
      } catch (e) { aspectRatio = null; }
      // Cores e referências: o mesmo pacote do Render decorado / galeria.
      let moduleRefImages = [], colorLabel = null, colorRefImages = [];
      try {
        const [refs, label, colorRefs] = await Promise.all([
          (typeof fetchReferencePhotosForProject === 'function') ? fetchReferencePhotosForProject() : { moduleRefImages: [] },
          (typeof buildColorDescriptionForProject === 'function') ? buildColorDescriptionForProject() : null,
          (typeof buildColorReferencesForProject === 'function') ? buildColorReferencesForProject() : []
        ]);
        moduleRefImages = (refs && refs.moduleRefImages) || [];
        colorLabel = label || null;
        colorRefImages = colorRefs || [];
      } catch (e) { console.warn('Render com IA: referências de cor/módulo indisponíveis', e); }
      const { data, error } = await supabaseClient.functions.invoke('generate-gallery-render', {
        body: { mode: 'enhance', imageDataUrl: baseDataUrl, aspectRatio, colorLabel, colorRefImages, moduleRefImages }
      });
      if (error || !data || !data.imageDataUrl) {
        let msg = (data && data.error) || (error && error.message) || 'erro';
        try { if (error && error.context && typeof error.context.json === 'function') { const b = await error.context.json(); if (b && b.error) msg = b.error; } } catch (e) { /* mantém */ }
        throw new Error(msg);
      }
      state.aiDataUrl = data.imageDataUrl;
      const ai = q('po-aiR-ai');
      ai.src = data.imageDataUrl; ai.style.display = 'block';
      setStatus('');
      // termo no fim, no idioma da tela
      state.lang = lang();
      state.termsText = TERMS[state.lang] || TERMS.pt;
      q('po-aiR-terms').textContent = state.termsText;
      q('po-aiR-pre').style.display = 'flex';
      const nm = q('po-aiR-name');
      if (!nm.value) { try { nm.value = (window.currentUserProfile && (currentUserProfile.full_name || currentUserProfile.name)) || ''; } catch (e) { /* vazio */ } }
    } catch (err) {
      console.error('Render com IA falhou:', err);
      setStatus(t('fail') + (err && err.message ? err.message : err), '#8a3b2e');
      q('po-aiR-after').style.display = 'flex';
      q('po-aiR-dl').style.display = 'none';
    }
  }

