// Bancada da janela de boas-vindas (portal-50). Rodar: node scripts/tests/teste-boas-vindas-tela.js js/portal-50-boas-vindas.js
const { JSDOM } = require('jsdom'); const fs = require('fs');
const src = fs.readFileSync(process.argv[2], 'utf8');
const dom = new JSDOM('<body><select id="po-unit-select"><option value="mm">mm</option><option value="in" selected>in</option></select><select id="po-weight-unit-select"><option value="kg">kg</option><option value="lb">lb</option></select><div id="po-proj-tb-help"><div class="po-tb-icons-row"></div></div></body>', { runScripts: 'outside-only', url: 'https://x.test/portal.html' });
const w = dom.window; const calls = [];
w.currentUser = { id: 'u1', email: 'a@b.c' };
let LG='pt'; w.I18n = { getLanguage: () => LG, setLanguage: (l) => { LG = l; } };
w.fetch = async () => ({ ok: false });
let estado = { needed: true, known: { name: 'Ana', phone: '' }, example_needed: false, video_needed: false };
w.supabaseClient = { rpc: async (n, a) => { calls.push([n, a]); if (n === 'my_onboarding') return { data: estado }; if (n === 'my_onboarding_submit') return { data: { ok: true } }; return { data: {} }; }, auth: { signOut: async () => {} } };
w.eval(src);
let fails = 0; const ok = (c, m) => { console.log((c ? ' ✓ ' : ' ✗ ') + m); if (!c) fails++; };
(async () => {
  await new Promise(r => setTimeout(r, 1200));
  const ov = w.document.getElementById('bv-ov');
  ok(!!ov, 'janela de cadastro aparece');
  ok(w.document.getElementById('bv-name').value === 'Ana', 'nome pré-preenchido');
  ok(!!w.document.getElementById('po-bv-video-btn'), 'botão do vídeo no HELP');
  ok(/Bem-vindo/.test(ov.textContent), 'texto em português');
  const form = ov.querySelector('form');
  form.dispatchEvent(new w.Event('submit', { cancelable: true }));
  await new Promise(r => setTimeout(r, 50));
  ok(/telefone/.test(w.document.getElementById('bv-err').textContent), 'sem telefone: avisa e não envia');
  ok(!calls.some(c => c[0] === 'my_onboarding_submit'), 'nada enviado ainda');
  const set = (id, v) => { w.document.getElementById(id).value = v; };
  set('bv-phone', '(352) 555-1234'); 
  ok(w.document.getElementById('bv-weight').value === 'lb', 'peso padrão lb');
  const lg = w.document.getElementById('bv-lang'); lg.value = 'en'; lg.dispatchEvent(new w.Event('change'));
  await new Promise(r => setTimeout(r, 30));
  ok(LG === 'en' && /Welcome/.test(w.document.getElementById('bv-ov').textContent), 'trocar idioma muda o portal e a janela');
  ok(w.document.getElementById('bv-phone').value === '(352) 555-1234', 'mantém o que já foi digitado');
  const form2 = w.document.querySelector('#bv-ov form');
  w.document.getElementById('bv-home').checked = true; w.document.getElementById('bv-home').dispatchEvent(new w.Event('change'));
  ok(w.document.getElementById('bv-company').disabled, 'homeowner trava o campo empresa');
  w.document.getElementById('bv-unit').value = 'mm';
  set('bv-line1', '1 Main St'); set('bv-city', 'Orlando'); set('bv-state', 'FL'); set('bv-zip', '32801');
  form2.dispatchEvent(new w.Event('submit', { cancelable: true }));
  await new Promise(r => setTimeout(r, 80));
  ok(w.document.getElementById('po-unit-select').value === 'mm' && w.document.getElementById('po-weight-unit-select').value === 'lb', 'unidade e peso aplicados no portal');
  ok(w.localStorage.getItem('legno_dim_unit') === 'mm', 'unidade fica salva');
  const sub = calls.find(c => c[0] === 'my_onboarding_submit');
  ok(sub && sub[1].p_homeowner === true && sub[1].p_zip === '32801', 'enviou pro banco');
  ok(!w.document.getElementById('bv-ov'), 'janela fecha depois de salvar');
  await new Promise(r => setTimeout(r, 1000));
  ok(calls.filter(c => c[0] === 'my_onboarding').length === 1, 'não pergunta de novo pro mesmo login');
  console.log(fails ? fails + ' FALHA(S)' : 'TUDO CERTO'); process.exit(fails ? 1 : 0);
})();
